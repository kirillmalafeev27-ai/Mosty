window.pickQuestion = function(cat) {
  const cats = cat === 'mix' ? Object.keys(QUESTIONS) : [cat];
  const c = cats[Math.floor(Math.random() * cats.length)];
  const bank = QUESTIONS[c];
  const item = bank[Math.floor(Math.random() * bank.length)];
  const correct = item.a[0];
  const shuffled = [...item.a].sort(() => Math.random() - 0.5);
  return {
    q: item.q,
    choices: shuffled,
    correctIndex: shuffled.indexOf(correct),
    correct
  };
};
